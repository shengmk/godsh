import { mkdtempSync, mkdirSync, writeFileSync, rmSync, existsSync, lstatSync, realpathSync, symlinkSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const root = mkdtempSync(join(tmpdir(), 'godsh-junction-probe-'))
const out = { node: process.version, platform: process.platform }

function probe(p) {
  let rp = null
  let err = null
  try { rp = realpathSync(p) } catch (e) { err = e.code }
  return {
    exists: existsSync(p),
    existsPkgJson: existsSync(join(p, 'package.json')),
    lstatIsSymlink: lstatSync(p).isSymbolicLink(),
    realpath: rp,
    realpathErr: err,
  }
}

